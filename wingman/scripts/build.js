// Generates public/config.js from environment variables at build time.
// Only PUBLIC values go into the browser: the Supabase project URL and the anon (publishable) key.
// The anon key is designed to be public; data is protected by Row Level Security (see supabase/schema.sql).
// NEVER put the service_role / secret key here — this script refuses it.
const fs = require("fs");
const path = require("path");

const url = (process.env.SUPABASE_URL || "").trim();
const key = (process.env.SUPABASE_ANON_KEY || "").trim();

function fail(msg) {
  console.error("\n[wingman build] " + msg + "\n");
  process.exit(1);
}

if (!url || !key) {
  fail("Missing SUPABASE_URL and/or SUPABASE_ANON_KEY. Set them in Vercel → Project → Settings → Environment Variables (or in a local .env).");
}
if (!/^https:\/\/[a-z0-9-]+\.supabase\.co\/?$/i.test(url)) {
  fail("SUPABASE_URL must look like https://YOUR-PROJECT-REF.supabase.co");
}
if (/^sb_secret_/.test(key)) {
  fail("SUPABASE_ANON_KEY is a SECRET key. Use the publishable/anon key instead. Aborting so it is never shipped to browsers.");
}
if (key.split(".").length === 3) {
  try {
    const payload = JSON.parse(Buffer.from(key.split(".")[1], "base64url").toString("utf8"));
    if (payload.role && payload.role !== "anon") {
      fail('SUPABASE_ANON_KEY has role "' + payload.role + '". Only the "anon" key may be used in the browser. Aborting.');
    }
  } catch (e) {
    fail("SUPABASE_ANON_KEY is not a valid key.");
  }
} else if (!/^sb_publishable_/.test(key)) {
  fail("SUPABASE_ANON_KEY is not recognised as an anon JWT or an sb_publishable_ key.");
}

const out = path.join(__dirname, "..", "public", "config.js");
const body =
  "// Generated by scripts/build.js — do not edit, do not commit.\n" +
  "window.WINGMAN_CONFIG = " +
  JSON.stringify({ supabaseUrl: url.replace(/\/$/, ""), supabaseAnonKey: key }) +
  ";\n";
fs.writeFileSync(out, body);
console.log("[wingman build] wrote public/config.js for " + url);
